/// A batch definition whose handler takes startup-injected parameters.
///
/// Generated by a `&[T]`-taking `#[subscriber]` handler when the signature carries
/// [`Out`](super::Out) parameters; [`Self::Injections`] is their
/// tuple, in declaration order. The metadata surface mirrors [`BatchDef`](super::BatchDef).
pub trait BatchInjectDef: MaybeSendSync {
    /// The input kind of one batch element (see [`BatchDef::Input`](super::BatchDef::Input)).
    type Input: InputKind;

    /// The subscription source this handler binds to.
    type Source;

    /// The tuple of startup-injected parameters ([`Out`](super::Out), ...).
    type Injections;

    /// The broker's typed subscription-scoped context the batch's handler reads by key (`()` when
    /// the handler names none); see [`BatchDef::Context`](super::BatchDef::Context).
    type Context;

    /// Builds the subscription source (fresh each call).
    fn source(&self) -> Self::Source;

    /// The concurrency policy for this subscriber's dispatch loop (how many batches are in
    /// flight at once).
    fn workers(&self) -> Workers {
        Workers::sequential()
    }

    /// The failure policy for a batch-handler panic and a per-element decode failure.
    fn failure_policies(&self) -> FailurePolicies {
        FailurePolicies::default()
    }

    /// An optional human description (from the handler's doc comment), for `AsyncAPI`.
    fn description(&self) -> Option<&str> {
        None
    }

    /// The element type's serialized JSON Schema, when available.
    #[cfg(ruststream_alloc)]
    fn input_schema(&self) -> Option<String> {
        None
    }

    /// The serialized JSON Schema of the element type's header contract, when one is declared.
    #[cfg(ruststream_alloc)]
    fn headers_schema(&self) -> Option<String> {
        None
    }

    /// The messages this handler publishes, for the `AsyncAPI` `send` operations: every `Out`
    /// slot dictionary entry. The macro fills this in; the default declares nothing. Called
    /// once at registration.
    #[cfg(ruststream_alloc)]
    fn outgoing(&self) -> Vec<OutgoingMessageMetadata> {
        Vec::new()
    }

    /// The element type's [`Message`](crate::MessageInfo) name, when it implements that trait.
    fn message_name(&self) -> Option<&'static str> {
        None
    }

    /// The element type's [`Message`](crate::MessageInfo) description, when it implements that
    /// trait.
    fn message_description(&self) -> Option<&'static str> {
        None
    }
}

/// Runs a [`BatchInjectDef`]'s handler body over an app state of type `S`.
///
/// The same state-generic shape as [`SliceHandler`](super::SliceHandler); see
/// [`PublishingCall`](super::PublishingCall) for the rationale.
#[cfg(ruststream_alloc)]
pub(crate) trait BatchInjectCall<S>: BatchInjectDef {
    /// Runs the handler body on one decoded batch, with the resolved injections.
    fn call(
        &self,
        batch: &[<Self::Input as InputKind>::Owned],
        injections: &Self::Injections,
        ctx: &mut Context<'_, Self::Context, S>,
    ) -> impl Future<Output = BatchResult> + MaybeSend;
}

/// Builds the registration metadata for an injected batch definition mounted under `name`.
#[cfg(ruststream_alloc)]
pub(crate) fn batch_inject_metadata<D: BatchInjectDef>(name: &str, def: &D) -> HandlerMetadata {
    let mut meta = HandlerMetadata::raw(name.to_owned()).with_def_details(
        def.description(),
        def.input_schema(),
        def.headers_schema(),
        def.message_name(),
        def.message_description(),
    );
    meta.input_type = <D::Input as InputKind>::input_label();
    meta.deserialized = <D::Input as InputKind>::DESERIALIZED;
    meta.outgoing = def.outgoing();
    meta
}

/// The batch handler built from a [`BatchInjectDef`] once its injections resolved: decode
/// the batch, run the body with them, settle every delivery.
#[cfg(ruststream_alloc)]
pub(crate) struct BatchInjectHandler<Def: BatchInjectDef, DecodeCodec> {
    pub(crate) def: Def,
    pub(crate) codec: DecodeCodec,
    pub(crate) injections: Def::Injections,
    pub(crate) decode: FailurePolicy,
}

#[cfg(ruststream_alloc)]
impl<Def: BatchInjectDef, DecodeCodec> fmt::Debug for BatchInjectHandler<Def, DecodeCodec> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("BatchInjectHandler").finish_non_exhaustive()
    }
}

#[cfg(ruststream_alloc)]
impl<Batch, Msg, Def, DecodeCodec, State> BatchHandler<Batch, Def::Context, State>
    for BatchInjectHandler<Def, DecodeCodec>
where
    Batch: BatchSlot<Message = Msg>,
    Msg: Settle,
    Def: BatchInjectCall<State>,
    Def::Input: DecodeWith<DecodeCodec>,
    Def::Injections: MaybeSendSync,
    Def::Context: BuildBatchContext<Msg> + MaybeSendSync + 'static,
    DecodeCodec: MaybeSendSync,
    State: MaybeSendSync,
{
    type Scratch = BatchVec<<Def::Input as InputKind>::Owned>;
    type Taken = BatchVec<Msg>;

    fn taken(size: NonZeroUsize) -> BatchVec<Msg> {
        BatchVec::with_room(size.get())
    }

    fn load(taken: &mut BatchVec<Msg>, slot: &mut Batch) {
        taken.extend(slot.drain());
    }

    #[cfg(ruststream_alloc)]
    async fn handle_batch<Host: SendHost<Def::Context>>(
        &self,
        batch: &mut BatchVec<Msg>,
        values: &mut Self::Scratch,
        ctx: &mut Context<'_, Def::Context, State>,
        host: &Host,
    ) {
        let subscription = ctx.subscription();
        decode_batch::<Msg, Def::Input, DecodeCodec, Def::Context, State, Host>(
            batch,
            values,
            &self.codec,
            self.decode,
            ctx,
            host,
        )
        .await;
        if batch.is_empty() {
            return;
        }
        let delivery = ctx.delivery();
        let mut result = self.def.call(values, &self.injections, ctx).await;
        values.clear();
        settle_batch(batch, &mut result, subscription, delivery, host).await;
    }
}

#[cfg(all(test, feature = "json"))]
mod tests {
    use alloc::format;
    use core::future::ready;
    use core::sync::atomic::{AtomicUsize, Ordering};
    use std::sync::{Arc, Mutex};

    use futures::StreamExt;
    use tokio_util::task::TaskTracker;

    use super::super::batch::handled;
    use super::super::dispatch::Delivery;
    use super::super::handler::HandlerOutcome;
    use super::super::input::Decoded;
    use super::*;
    use crate::codec::JsonCodec;
    use crate::testkit::Tracked;
    use crate::testkit::batch::{publish_payloads, pull_batch};
    use crate::{HeaderSet, Name, Subscriber, SubscriptionSource};
    use ruststream::memory::{ConnectedMemoryBroker, MemoryBroker};

    /// A definition whose "injection" is a plain multiplier: the real ones are `Out`
    /// values, but the handler side only cares that the resolved tuple is handed to every call.
    struct Scale {
        calls: Arc<AtomicUsize>,
        seen: Arc<Mutex<BatchVec<u32>>>,
    }

    impl Scale {
        fn new() -> Self {
            Self {
                calls: Arc::new(AtomicUsize::new(0)),
                seen: Arc::new(Mutex::new(Vec::new())),
            }
        }
    }

    impl BatchInjectDef for Scale {
        type Input = Decoded<u32>;
        type Source = Name;
        type Injections = u32;
        type Context = ();

        fn source(&self) -> Self::Source {
            Name::new("scale")
        }
    }

    // Ignores the app state, so it is generic over it (mounts on any app).
    impl<S: MaybeSendSync> BatchInjectCall<S> for Scale {
        fn call(
            &self,
            batch: &[u32],
            factor: &u32,
            _ctx: &mut Context<'_, (), S>,
        ) -> impl Future<Output = BatchResult> {
            self.calls.fetch_add(1, Ordering::SeqCst);
            self.seen
                .lock()
                .expect("seen mutex poisoned")
                .extend(batch.iter().map(|n| n * factor));
            ready(BatchResult::Uniform(HandlerOutcome::ack()))
        }
    }

    #[test]
    fn batch_inject_def_defaults_register_without_documentation() {
        let def = Scale::new();
        // The mount site names the registration after the def's own source.
        let source = def.source();
        let name = SubscriptionSource::<ConnectedMemoryBroker>::name(&source);
        let meta = batch_inject_metadata(name, &def);

        assert_eq!(meta.name, "scale");
        assert_eq!(meta.input_type, "u32");
        assert!(meta.description.is_none());
        assert!(meta.payload_schema.is_none());
        assert!(meta.headers_schema.is_none());
        assert!(meta.message_name.is_none());
        assert!(meta.message_description.is_none());
        assert!(meta.outgoing.is_empty());
        assert_eq!(def.workers(), Workers::sequential());
        assert_eq!(def.failure_policies(), FailurePolicies::default());
    }

    /// The handler names itself and elides the definition, the codec and the resolved injections
    /// it carries.
    #[test]
    fn the_handler_renders_its_name_alone() {
        let handler = BatchInjectHandler {
            def: Scale::new(),
            codec: JsonCodec,
            injections: 10,
            decode: FailurePolicy::Drop,
        };
        assert_eq!(format!("{handler:?}"), "BatchInjectHandler { .. }");
    }

    /// The resolved injections reach every call alongside the decoded batch, and the returned
    /// settlement is applied to the deliveries behind it.
    #[tokio::test]
    async fn resolved_injections_reach_the_body_with_the_batch() {
        let broker = MemoryBroker::new();
        let mut sub = broker.subscribe("scale");
        publish_payloads(&broker, "scale", &[b"1", b"2"]).await;

        let def = Scale::new();
        let seen = Arc::clone(&def.seen);
        let handler = BatchInjectHandler {
            def,
            codec: JsonCodec,
            injections: 10,
            decode: FailurePolicy::Drop,
        };

        let state = ();
        let delivery = Delivery::empty();
        let host = Tracked(TaskTracker::new());
        let headers = HeaderSet::new();
        let mut ctx = Context::new("scale", &headers, &state, (), &delivery);
        let batch = pull_batch(&mut sub).await;
        assert_eq!(batch.len(), 2);
        handled(&handler, batch, &mut Vec::new(), &mut ctx, &host).await;

        assert_eq!(*seen.lock().unwrap(), [10, 20]);
        // The uniform Ack settled both deliveries, so neither comes back.
        let mut stream = core::pin::pin!(sub.stream());
        assert!(futures::poll!(stream.next()).is_pending());
    }

    /// Every element failing to decode short-circuits: the body is not invoked with an empty
    /// slice, and the dropped elements are not requeued.
    #[tokio::test]
    async fn a_fully_undecodable_batch_never_reaches_the_body() {
        let broker = MemoryBroker::new();
        let mut sub = broker.subscribe("scale");
        publish_payloads(&broker, "scale", &[b"not json", b"also not json"]).await;

        let def = Scale::new();
        let calls = Arc::clone(&def.calls);
        let handler = BatchInjectHandler {
            def,
            codec: JsonCodec,
            injections: 10,
            decode: FailurePolicy::Drop,
        };

        let state = ();
        let delivery = Delivery::empty();
        let host = Tracked(TaskTracker::new());
        let headers = HeaderSet::new();
        let mut ctx = Context::new("scale", &headers, &state, (), &delivery);
        let batch = pull_batch(&mut sub).await;
        assert_eq!(batch.len(), 2);
        handled(&handler, batch, &mut Vec::new(), &mut ctx, &host).await;

        assert_eq!(calls.load(Ordering::SeqCst), 0);
        let mut stream = core::pin::pin!(sub.stream());
        assert!(futures::poll!(stream.next()).is_pending());
    }
}
